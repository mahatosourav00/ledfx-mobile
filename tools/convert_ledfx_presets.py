"""Converts LedFx's built-in effect presets (ledfx/presets.py) into Kotlin.

Usage: py -3 -I tools/convert_ledfx_presets.py <path to ledfx/presets.py> <output .kt>
Only effects that exist in the app are kept; LedFx-only keys are dropped at runtime.
"""
import ast
import json
import re
import sys

APP_EFFECTS = {
    "energy", "spectrum", "wavelength", "scroll", "scroll_plus", "power", "magnitude",
    "pitchSpectrum", "blade_power_plus", "rain", "real_strobe", "scan", "scan_and_flare",
    "scan_multi", "spotlight", "bar", "multiBar", "strobe", "fire", "block_reflections",
    "crawler", "energy2", "glitch", "lava_lamp", "marching", "melt", "melt_and_sparkle",
    "water", "filter", "hierarchy", "vumeter", "bands", "bands_matrix", "blocks",
    "equalizer", "gradient", "fade", "rainbow", "singleColor", "random_flash",
}
NAMED_GRADIENTS = {
    "Rainbow": [0xFF0000, 0xFF7800, 0xFFC800, 0x00FF00, 0x00C78C, 0x0000FF, 0x800080, 0xFF00B2],
    "Dancefloor": [0xFF0000, 0xFF00B2, 0x0000FF],
    "Plasma": [0x0000FF, 0x800080, 0xFF0000, 0xFF2800, 0xFFC800],
    "Ocean": [0x00FFFF, 0x0000FF],
    "Viridis": [0x800080, 0x0000FF, 0x008080, 0x00FF00, 0xFFC800],
    "Jungle": [0x00FF00, 0x228B22, 0xFF7800],
    "Spring": [0xFF00B2, 0xFF2800, 0xFFC800],
    "Winter": [0x00C78C, 0x00FF32],
    "Frost": [0x0000FF, 0x00FFFF, 0x800080, 0xFF00B2],
    "Sunset": [0x000080, 0xFF7800, 0xFF0000],
    "Borealis": [0xFF2800, 0x800080, 0x00C78C, 0x00FF00],
    "Rust": [0xFF2800, 0xFF0000],
    "Winamp": [0x00FF00, 0xFFC800, 0xFF7800, 0xFF2800, 0xFF0000],
}
SKIP = {"background_brightness", "background_mode", "diag", "dump", "brightness",
        "flip_horizontal_", "rotate", "test", "advanced", "gradient_name", "solid_color",
        "gradient_repeat", "color_correction"}


def colors_of(s):
    out = []
    for m in re.finditer(r"#([0-9a-fA-F]{6})|rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)", s):
        if m.group(1):
            out.append(int(m.group(1), 16))
        else:
            r, g, b = (int(m.group(i)) for i in (2, 3, 4))
            out.append((r << 16) | (g << 8) | b)
    return out


def kt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v}"
    if isinstance(v, float):
        return f"{v}f"
    return json.dumps(v, ensure_ascii=False).replace("$", "\\$")


def main(src, dst):
    presets = ast.literal_eval(ast.parse(open(src, encoding="utf-8").read()).body[0].value)
    lines = []
    for effect, items in presets.items():
        if effect not in APP_EFFECTS:
            continue
        for pid, preset in items.items():
            cfg = preset["config"]
            gradient = None
            values = []
            for k, v in cfg.items():
                if k in SKIP:
                    continue
                if k == "gradient":
                    gradient = NAMED_GRADIENTS.get(v) if v in NAMED_GRADIENTS else colors_of(v)
                    continue
                if isinstance(v, str) and k != "frequency_range" and (v.startswith("#") or v.startswith("rgb")):
                    c = colors_of(v)
                    v = c[0] if c else v
                values.append(f'"{k}" to {kt(v)}')
            grad = "null" if not gradient else "listOf(" + ", ".join(f"0x{c:06X}" for c in gradient) + ")"
            lines.append(
                f'        Preset("ledfx:{effect}:{pid}", {json.dumps(preset["name"], ensure_ascii=False)}, "{effect}", '
                f'mapOf({", ".join(values)}), {grad}),'
            )
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/convert_ledfx_presets.py from LedFx's presets.py. Do not edit.\n")
        f.write("package org.ledfxmobile.app.effects\n\n")
        f.write("object LedFxPresets {\n    val all: List<Preset> = listOf(\n")
        f.write("\n".join(lines))
        f.write("\n    )\n}\n")
    print(f"{len(lines)} presets written")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
